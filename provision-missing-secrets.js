/**
 * Provisions the two Parameter Store secrets that PR #620's startup gate
 * requires but `/aura/prod` does not yet have:
 *
 *   AUTH_RECOVERY_CODE_SECRET  - recovery-code HMAC key (long-lived bearer creds)
 *   SECURITY_LOG_HASH_KEY      - security-log pseudonymisation key
 *
 * Both were silently falling back to OTP_FLOW_SECRET. Values are generated
 * locally and passed straight to SSM as SecureString; the plaintext is never
 * printed and never written to disk.
 *
 * Idempotent: skips creation if the parameter already exists, so a re-run after
 * a partial failure cannot clobber an in-use secret.
 *
 * Usage: node provision-missing-secrets.js --dry-run
 *        node provision-missing-secrets.js
 */
const { execFileSync } = require('child_process');
const crypto = require('crypto');

const PROFILE = 'aura-new-admin';
const REGION = 'ap-south-1';
const PATH_PREFIX = '/aura/prod';
const KMS_KEY_ALIAS = 'alias/aura-field-encryption';

const dryRun = process.argv.includes('--dry-run');

const TARGETS = [
    { name: 'AUTH_RECOVERY_CODE_SECRET', bytes: 48 },
    { name: 'SECURITY_LOG_HASH_KEY', bytes: 48 },
];

const aws = (args) => execFileSync('aws', [
    ...args,
    '--profile', PROFILE,
    '--region', REGION,
    '--output', 'json',
], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });

const parameterExists = (name) => {
    try {
        aws(['ssm', 'get-parameter', '--name', name]);
        return true;
    } catch {
        return false;
    }
};

const run = async () => {
    console.log(`profile=${PROFILE} region=${REGION} dryRun=${dryRun}\n`);

    for (const target of TARGETS) {
        const fullName = `${PATH_PREFIX}/${target.name}`;

        if (parameterExists(fullName)) {
            console.log(`SKIP  ${target.name} (already exists — not overwriting)`);
            // eslint-disable-next-line no-continue
            continue;
        }

        // 48 random bytes, base64url: ~288 bits, well above the 32-char minimum
        // the config validators enforce, and not a human passphrase.
        const value = crypto.randomBytes(target.bytes).toString('base64url');

        if (dryRun) {
            console.log(`WOULD CREATE  ${target.name}  (SecureString, ${target.bytes} random bytes)`);
            // eslint-disable-next-line no-continue
            continue;
        }

        aws([
            'ssm', 'put-parameter',
            '--name', fullName,
            '--type', 'SecureString',
            '--value', value,
            '--key-id', KMS_KEY_ALIAS,
            '--description', 'Generated by provision-missing-secrets.js for crypto domain separation (PR #620)',
        ]);

        console.log(`CREATED  ${target.name}  (SecureString)`);
    }

    // Verify the end state without printing values.
    const params = JSON.parse(aws(['ssm', 'get-parameters-by-path', '--path', PATH_PREFIX, '--recursive']));
    const present = new Set((params.Parameters || []).map((p) => String(p.Name).replace(`${PATH_PREFIX}/`, '')));

    console.log('\n--- verification ---');
    const required = [
        'PHONE_BLIND_INDEX_SECRET',
        'EMAIL_BLIND_INDEX_SECRET',
        'OTP_HASH_SECRET',
        'AUTH_RECOVERY_CODE_SECRET',
        'OTP_FLOW_SECRET',
        'SECURITY_LOG_HASH_KEY',
        'MFA_SECRET_ENCRYPTION_KEY',
        'FIELD_ENCRYPTION_ENABLED',
        'FIELD_ENCRYPTION_KMS_KEY_ID',
    ];
    let missing = 0;
    for (const key of required) {
        const ok = present.has(key);
        if (!ok) missing += 1;
        console.log(`${ok ? 'PRESENT' : 'MISSING'}  ${key}`);
    }
    console.log(`\n${required.length - missing}/${required.length} required secrets present`);
    if (missing > 0 && !dryRun) process.exitCode = 1;
};

run().catch((error) => {
    console.error(`FAILED: ${error.message}`);
    process.exitCode = 1;
});
